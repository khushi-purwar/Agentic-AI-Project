from pydantic import BaseModel, Field
from typing import List, Annotated, Literal
from operator import add

class AgentSchema(BaseModel):
    messages : Annotated[list, add] =  Field(description="List of messages to be processed by the agent")
    user_input: str = Field(description="The input provided by the user")
    curated_question: str = Field(description="Curated user question")
    prompt_query_context: str = Field(description="A detailed prompt with SQL DB context that will help agent to generate SQL Query")
    generated_sql_query: str = Field(description="The SQL query generated by the agent based on the curated question")
    is_safe: Literal["Yes", "No"] = Field(description="Indicates whether the generated SQL query is safe")
    comments: str = Field(description="Comments or feedback regarding the safety of the generated SQL query")
    sql_query_execution_result: str = Field(description="The result of executing the generated SQL query")
    final_answer: str = Field(description="The final answer provided by the agent based on the SQL query execution result")

class JudgeSchema(BaseModel):
    answer: Literal["Yes", "No"] = Field(description="Indicates whether the generated SQL query is safe to execute or not")
    comments: str = Field(description="Additional comments or feedback from the judge regarding the SQL query.")


class ETLAgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(description="List of messages to be processed by the ETL agent")

class RouterSchema(BaseModel):
    answer: Literal["sql", "etl"] = Field(description="Indicates whether the routing decision is for the SQL agent or the ETL agent")
    comments: str = Field(description="Additional comments or feedback regarding the routing decision")

class DataAgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(description="List of messages to be processed by the Data agent")
    route_response: str = Field(description="The routing decision made by the Data agent")
